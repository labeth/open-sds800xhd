// Command genrates writes the sample-rate tables of spec 04 §4.2–§4.4 as Go.
//
//	go run ./internal/genrates ../../../specs/04-timebase-and-bands.md > rates_gen.go
package main

import (
	"bufio"
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
)

var row = regexp.MustCompile(`^\|\s*(\d+)\s*\|[^|]*\|(.*)\|\s*$`)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genrates SPEC04")
		os.Exit(2)
	}
	b, err := os.ReadFile(os.Args[1]) //nolint:gosec // G703: a development tool reading the spec file its caller names
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	txt := string(b)
	var tables [3][][]float64
	for i, name := range []string{"4.2 Route 1ch", "4.3 Route 2ch", "4.4 Route 4ch"} {
		at := strings.Index(txt, name)
		if at < 0 {
			fail("section %q not found", name)
		}
		sc := bufio.NewScanner(strings.NewReader(txt[at:]))
		sc.Scan()
		for sc.Scan() {
			line := sc.Text()
			if strings.HasPrefix(line, "####") || strings.HasPrefix(line, "## ") {
				break
			}
			m := row.FindStringSubmatch(line)
			if m == nil {
				continue
			}
			var vals []float64
			for f := range strings.SplitSeq(m[2], "|") {
				v, err := strconv.ParseFloat(strings.TrimSpace(f), 64)
				if err != nil {
					fail("%s: %q: %v", name, line, err)
				}
				vals = append(vals, v)
			}
			if len(vals) == 5 {
				vals = append(vals, vals[4])
			}
			if len(vals) != 6 {
				fail("%s: %q: %d columns", name, line, len(vals))
			}
			tables[i] = append(tables[i], vals)
		}
		if len(tables[i]) != 39 {
			fail("%s: %d rows, want 39", name, len(tables[i]))
		}
	}
	// bufio.Writer keeps the first write error and Flush returns it.
	w := bufio.NewWriter(os.Stdout)
	_, _ = fmt.Fprint(w, "// Code generated by internal/genrates from specs/04-timebase-and-bands.md §4.2–§4.4; DO NOT EDIT.\n\n")
	_, _ = fmt.Fprint(w, "package timebase\n\n")
	_, _ = fmt.Fprint(w, "// rateTable[route][time/div enum][column] is the table sample rate in MSa/s; columns 0–3 are\n")
	_, _ = fmt.Fprint(w, "// depth enums 0–3, 4 is depth enum 4 with the full depth set, 5 with the limited set.\n")
	_, _ = fmt.Fprint(w, "var rateTable = [3][39][6]float64{\n")
	for _, t := range tables {
		_, _ = fmt.Fprint(w, "\t{\n")
		for _, r := range t {
			s := make([]string, len(r))
			for i, v := range r {
				s[i] = strconv.FormatFloat(v, 'g', -1, 64)
			}
			_, _ = fmt.Fprintf(w, "\t\t{%s},\n", strings.Join(s, ", "))
		}
		_, _ = fmt.Fprint(w, "\t},\n")
	}
	_, _ = fmt.Fprint(w, "}\n")
	if err := w.Flush(); err != nil {
		fail("write: %v", err)
	}
}

func fail(f string, a ...any) {
	fmt.Fprintf(os.Stderr, "genrates: "+f+"\n", a...)
	os.Exit(1)
}
